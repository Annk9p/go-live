// สร้าง components/icons.tsx จาก Boxicons (outline/regular) — ห้ามแก้ไฟล์ปลายทางด้วยมือ แก้ MAP ที่นี่แล้วรัน `npm run icons`
import { readFileSync, writeFileSync } from "node:fs";
const MAP = {
  Calendar: "calendar", CalendarWeek: "calendar-week", User: "user", UserCircle: "user-circle", Group: "group",
  Store: "store", ChevronDown: "chevron-down", ChevronLeft: "chevron-left", ChevronRight: "chevron-right",
  Grid: "grid-alt", Import: "import", Cog: "cog", File: "file", Menu: "menu", X: "x", Plus: "plus",
  Edit: "edit", Trash: "trash", Error: "error", Time: "time-five", Refresh: "refresh", Check: "check",
  Table: "table", Moon: "moon", Sun: "sun", BarChart: "bar-chart-alt-2", History: "history", Undo: "undo",
  Download: "cloud-download", Shield: "shield-quarter", List: "list-ul", ErrorCircle: "error-circle",
  InfoCircle: "info-circle", CheckCircle: "check-circle", Data: "data", Sync: "sync", Sheet: "spreadsheet",
  Broadcast: "broadcast", Live: "video-recording", Search: "search", Filter: "filter-alt",
  Bell: "bell", Swap: "transfer-alt", CheckDouble: "check-double", Power: "power-off",
  TiktokLogo: "logos:tiktok",
};
let out = `// AUTO-GENERATED by scripts/gen-icons.mjs from Boxicons (MIT). Do not edit by hand.\nimport type { SVGProps } from "react";\n\ntype P = SVGProps<SVGSVGElement> & { size?: number };\nconst base = ({ size = 16, ...p }: P) => ({ width: size, height: size, viewBox: "0 0 24 24", fill: "currentColor", "aria-hidden": p["aria-label"] ? undefined : true, ...p });\n\n`;
for (const [name, file] of Object.entries(MAP)) {
  // "logos:ชื่อ" = โลโก้แบรนด์จาก boxicons/svg/logos (bxl-*) · อื่น ๆ = outline (bx-*)
  const svg = file.startsWith("logos:")
    ? readFileSync(`node_modules/boxicons/svg/logos/bxl-${file.slice(6)}.svg`, "utf8")
    : readFileSync(`node_modules/boxicons/svg/regular/bx-${file}.svg`, "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => `<path d="${m[1]}" />`).join("");
  out += `export const ${name} = (p: P) => <svg {...base(p)}>${paths}</svg>;\n`;
}
writeFileSync("components/icons.tsx", out);
console.log("icons:", Object.keys(MAP).length);
